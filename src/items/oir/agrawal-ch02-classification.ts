// ---------------------------------------------------------------- numbers
/** The numbers printed in an option ("11 – 122" → [11, 122]; "4/5 : 3" → [4, 5, 3]). */
const nums = (s: string) => [...s.matchAll(/\d+(?:\.\d+)?/g)].map((m) => Number(m[0]));
/** A rule on the pair a – b. */
const pair = (f: (a: number, b: number) => boolean) => (s: string) => {
  const [a, b] = nums(s);
  return f(a, b);
};
const digits = (n: number) => [...String(n)].map(Number);
const dsum = (n: number) => digits(n).reduce((s, d) => s + d, 0);
const dprod = (n: number) => digits(n).reduce((s, d) => s * d, 1);
const rev = (n: number) => Number([...String(n)].reverse().join(''));
const isPrime = (n: number) => {
  if (!Number.isInteger(n) || n < 2) return false;
  for (let i = 2; i * i <= n; i++) if (n % i === 0) return false;
  return true;
};
const nextPrime = (n: number) => {
  let m = n + 1;
  while (!isPrime(m)) m++;
  return m;
};
const isSquare = (n: number) => Number.isInteger(Math.sqrt(n));
const cbrt = (n: number) => Math.round(Math.cbrt(n));

// ---------------------------------------------------------------- letters
const p = (c: string) => c.toUpperCase().charCodeAt(0) - 64;
/** Signed gaps between neighbouring letters. */
